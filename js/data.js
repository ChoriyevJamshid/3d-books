/** Estimated reading time for a book in minutes (≈ 220 words per minute). */
export function readingMinutes(book) {
  const words = book.content.reduce((n, p) => {
    const text = [p.title, p.caption, p.q, ...(p.p || [])].filter(Boolean).join(" ");
    return n + text.split(/\s+/).length;
  }, 0);
  return Math.max(1, Math.round(words / 220));
}

